"""
Builds src/components/admin/emoji-data.ts (the newsletter editor's emoji picker) from two open data sets:
emojibase-data (MIT: emoji, group, English name + tags) and cldr-annotations-full (Unicode license: Arabic names).
Only emoji up to Unicode 15.0, so phones and mail apps from the last few years can show them all.

    mkdir -p /tmp/emoji && cd /tmp/emoji && npm pack emojibase-data cldr-annotations-full
    mkdir a b && tar xzf emojibase-data-*.tgz -C a && tar xzf cldr-annotations-full-*.tgz -C b
    python3 scripts/emoji-data.py /tmp/emoji/a/package /tmp/emoji/b/package
"""
import json
import sys
from pathlib import Path

base, cldr = Path(sys.argv[1]), Path(sys.argv[2])
data = json.loads((base / "en/data.json").read_text())
ar = json.loads((cldr / "annotations/ar/annotations.json").read_text())["annotations"]["annotations"]

# emojibase group number -> picker group key (2 = skin tone components, left out).
GROUPS = {0: "smileys", 1: "people", 3: "nature", 4: "food", 5: "travel", 6: "activities", 7: "objects", 8: "symbols", 9: "flags"}
out = {key: [] for key in GROUPS.values()}

for e in sorted(data, key=lambda e: e.get("order", 0)):
    if e.get("group") not in GROUPS or e.get("version", 99) > 15.0:
        continue
    emoji = e["emoji"]
    names = ar.get(emoji) or ar.get(emoji.replace("️", "")) or {}
    words = [e["label"], *e.get("tags", []), *names.get("tts", []), *names.get("default", [])[:5]]
    search = " ".join(dict.fromkeys(w.lower() for w in words))
    out[GROUPS[e["group"]]].append([emoji, search])

lines = [
    "// Generated by scripts/emoji-data.py (emojibase-data, MIT + Unicode CLDR names). Do not edit by hand.",
    "",
    "/** Picker groups in order; each emoji comes with its English and Arabic names for search. */",
    "export const EMOJI_GROUPS: { key: string; items: [emoji: string, search: string][] }[] = [",
]
for key, items in out.items():
    lines.append(f"  {{ key: {json.dumps(key)}, items: {json.dumps(items, ensure_ascii=False, separators=(',', ':'))} }},")
lines.append("];")
lines.append("")
target = Path(__file__).resolve().parent.parent / "src/components/admin/emoji-data.ts"
target.write_text("\n".join(lines))
print(f"{sum(len(v) for v in out.values())} emoji -> {target} ({target.stat().st_size // 1024} KB)")
